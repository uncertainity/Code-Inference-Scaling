MOD = 998244353
N, M = map(int, input().split())

# 一人目の値を固定する（最後にM倍する）
same = 1 # 現在の人が一人目と同じ値になるような選び方の総数
diff = 0 # 現在の人が一人目と違う値になるような選び方の総数

for _ in range(N - 1):
    new_same = diff # 現在の人が一人目と同じ値になるには、直前の人が一人目と違う値である必要がある
    new_diff = (
        same * (M - 1) # 直前の人が一人目と同じ値の場合、現在の人は一人目以外の値なら何でもよいので、M-1通りから選べる
        + diff * (M - 2) # 直前の人が一人目と違う値の場合、現在の人は一人目と直前の人のどちらとも違う値である必要があるので、M-2通りから選べる
    ) % MOD
    
    same, diff = new_same, new_diff

print(diff * M % MOD) # 円環なのでN人目は一人目と違う値である必要がある。一人目の値の選び方はM通りあるのでM倍する